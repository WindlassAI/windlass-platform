// Writes runner/src/public-suffixes.ts from the Public Suffix List (https://publicsuffix.org/list/).
//   node scripts/public-suffix-update.mjs                 fetch the current list from publicsuffix.org
//   node scripts/public-suffix-update.mjs <file.dat>      use a downloaded copy
// The output keeps the list's version, commit and digest, and only its rules (comments dropped,
// internationalized names in their ASCII form, as a hostname reaches the proxy).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const SOURCE = "https://publicsuffix.org/list/public_suffix_list.dat";
const text = process.argv[2] ? readFileSync(process.argv[2], "utf8") : await (await fetch(SOURCE)).text();
const version = /^\/\/ VERSION: (\S+)$/m.exec(text)?.[1];
const commit = /^\/\/ COMMIT: ([0-9a-f]{40})$/m.exec(text)?.[1];
if (!version || !commit || !text.includes("===BEGIN PRIVATE DOMAINS===")) throw new Error("not the Public Suffix List from " + SOURCE);
const rules = new Set();
for (const line of text.split("\n")) {
	const rule = line.trim().split(/\s/)[0];
	if (!rule || rule.startsWith("//")) continue;
	const [prefix, name] = rule.startsWith("*.") ? ["*.", rule.slice(2)] : rule.startsWith("!") ? ["!", rule.slice(1)] : ["", rule];
	const ascii = domainToASCII(name);
	if (!ascii || ascii.includes("*") || !/^[a-z0-9.-]+$/.test(ascii)) throw new Error("unexpected rule " + rule);
	rules.add(prefix + ascii);
}
const digest = createHash("sha256").update(text).digest("hex");
const out = `// Generated by scripts/public-suffix-update.mjs: do not edit.
// The Public Suffix List, ${SOURCE}
// VERSION ${version}, COMMIT ${commit} (github.com/publicsuffix/list), sha256 ${digest}.
// ICANN and private sections, rules only, ${rules.size} of them.
//
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.

export const PUBLIC_SUFFIX_VERSION = ${JSON.stringify(version)};
export const PUBLIC_SUFFIX_RULES = ${JSON.stringify([...rules].join(" "))};
`;
writeFileSync(new URL("../runner/src/public-suffixes.ts", import.meta.url), out);
console.log(`public-suffixes.ts: ${rules.size} rules, version ${version}`);
